// Language setup. Polish is the default (no URL prefix); every other language lives
// under /<code>/. Polish pages have Polish slugs; the others share English slugs.
export const languages = {
  pl: { name: 'Polski', locale: 'pl-PL', hreflang: 'pl', og: 'pl_PL', dir: 'ltr' },
  en: { name: 'English', locale: 'en-GB', hreflang: 'en', og: 'en_US', dir: 'ltr' },
  de: { name: 'Deutsch', locale: 'de-DE', hreflang: 'de', og: 'de_DE', dir: 'ltr' },
  es: { name: 'Español', locale: 'es-ES', hreflang: 'es', og: 'es_ES', dir: 'ltr' },
  fr: { name: 'Français', locale: 'fr-FR', hreflang: 'fr', og: 'fr_FR', dir: 'ltr' },
  it: { name: 'Italiano', locale: 'it-IT', hreflang: 'it', og: 'it_IT', dir: 'ltr' },
  ar: { name: 'العربية', locale: 'ar', hreflang: 'ar', og: 'ar_AR', dir: 'rtl' },
  ja: { name: '日本語', locale: 'ja-JP', hreflang: 'ja', og: 'ja_JP', dir: 'ltr' },
  zh: { name: '简体中文', locale: 'zh-CN', hreflang: 'zh-Hans', og: 'zh_CN', dir: 'ltr' },
} as const;

export type Lang = keyof typeof languages;
export const defaultLang: Lang = 'pl';
export const langs = Object.keys(languages) as Lang[];
export const prefixedLangs = langs.filter((l) => l !== defaultLang);

const pages = {
  home: { pl: '/', other: '' },
  blog: { pl: '/blog', other: '/blog' },
  contact: { pl: '/kontakt', other: '/contact' },
  privacy: { pl: '/polityka-prywatnosci', other: '/privacy' },
} as const;
export type RouteKey = keyof typeof pages;

export function route(key: RouteKey, lang: Lang): string {
  return lang === defaultLang ? pages[key].pl : `/${lang}${pages[key].other}`;
}

/** URL of a page in every language — feeds hreflang and the language switcher. */
export function routeAlternates(key: RouteKey): Record<Lang, string> {
  return Object.fromEntries(langs.map((l) => [l, route(key, l)])) as Record<Lang, string>;
}

/** Footer menu (the header is the newsletter sign-up). */
export const navOrder: RouteKey[] = ['blog', 'contact'];

export function postUrl(lang: Lang, slug: string) {
  return `${route('blog', lang)}/${slug}`;
}

export function rssUrl(lang: Lang) {
  return lang === defaultLang ? '/rss.xml' : `/${lang}/rss.xml`;
}

export function formatDate(date: Date, lang: Lang) {
  return date.toLocaleDateString(languages[lang].locale, { year: 'numeric', month: 'long', day: 'numeric' });
}

/** Compact date for list rows, e.g. "15 paź 2026". */
export function formatDateShort(date: Date, lang: Lang) {
  return date.toLocaleDateString(languages[lang].locale, { year: 'numeric', month: 'short', day: 'numeric' });
}

/** Pick a localized value, falling back to English, then Polish. */
export function pick<T>(value: Partial<Record<Lang, T>>, lang: Lang): T {
  return (value[lang] ?? value.en ?? value.pl) as T;
}

